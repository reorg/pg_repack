--
-- repack.get_compare_pkey must emit schema-qualified equality operators, so
-- that repack.repack_apply (which runs with search_path = pg_catalog, pg_temp)
-- works for key types whose "=" operator lives outside pg_catalog.
--

-- A base type with no operators in pg_catalog, reusing the int4 functions.
SET client_min_messages = warning;
CREATE TYPE public.cmpt;
CREATE FUNCTION public.cmpt_in(cstring) RETURNS public.cmpt LANGUAGE internal IMMUTABLE STRICT AS 'int4in';
CREATE FUNCTION public.cmpt_out(public.cmpt) RETURNS cstring LANGUAGE internal IMMUTABLE STRICT AS 'int4out';
CREATE TYPE public.cmpt (INPUT = public.cmpt_in, OUTPUT = public.cmpt_out, LIKE = int4);
CREATE FUNCTION public.cmpt_eq(public.cmpt, public.cmpt) RETURNS boolean LANGUAGE internal IMMUTABLE STRICT AS 'int4eq';
CREATE FUNCTION public.cmpt_cmp(public.cmpt, public.cmpt) RETURNS integer LANGUAGE internal IMMUTABLE STRICT AS 'btint4cmp';
CREATE OPERATOR public.= (LEFTARG = public.cmpt, RIGHTARG = public.cmpt, PROCEDURE = public.cmpt_eq);
CREATE OPERATOR CLASS public.cmpt_ops DEFAULT FOR TYPE public.cmpt USING btree AS
    OPERATOR 3 public.=,
    FUNCTION 1 public.cmpt_cmp(public.cmpt, public.cmpt);

RESET client_min_messages;

-- Table with a primary key of that type
CREATE TABLE cmp_t (id public.cmpt PRIMARY KEY, val text);

-- The key comparison must use a schema-qualified operator
SELECT repack.get_compare_pkey('cmp_t_pkey'::regclass, '$1');

-- Apply a log containing an UPDATE and a DELETE with repack.repack_apply,
-- using the SQL generated by the repack.tables view.
SELECT 'cmp_t'::regclass::oid AS oid, indexrelid AS pkid
  FROM pg_index WHERE indrelid = 'cmp_t'::regclass AND indisprimary
\gset

-- Create the objects pg_repack would create: key type, log table, copy table
INSERT INTO cmp_t VALUES ('1', 'x'), ('2', 'y'), ('3', 'z');
SELECT repack.create_index_type(:pkid, :oid);
SELECT repack.create_log_table(:oid);
CREATE TABLE repack.table_:oid (LIKE public.cmp_t);
INSERT INTO repack.table_:oid SELECT * FROM public.cmp_t;

-- Get the generated SQL used to replay the log
SELECT sql_peek, sql_insert, sql_delete, sql_update, sql_pop
  FROM repack.tables WHERE relname = 'public.cmp_t'
\gset
-- Log an UPDATE of row 2 and a DELETE of row 3
INSERT INTO repack.log_:oid (pk, row) VALUES
  (ROW('2')::repack.pk_:oid, ROW('2', 'Y')::public.cmp_t),
  (ROW('3')::repack.pk_:oid, NULL);

-- Replay the log under the pinned search_path
-- Without the schema-qualified operator this fails with:
-- ERROR:  operator does not exist: public.cmpt = public.cmpt
SELECT repack.repack_apply(:'sql_peek', :'sql_insert', :'sql_delete', :'sql_update', :'sql_pop', 100);
-- Row 2 is updated, row 3 is deleted, and the log is drained
SELECT * FROM repack.table_:oid ORDER BY id::text;
SELECT count(*) AS remaining_log_rows FROM repack.log_:oid;

-- Cleanup
DROP TABLE repack.log_:oid;
DROP TABLE repack.table_:oid;
DROP TYPE repack.pk_:oid;
DROP TABLE cmp_t;
-- CASCADE also drops the dependent functions, operator and operator class
SET client_min_messages = warning;
DROP TYPE public.cmpt CASCADE;
RESET client_min_messages;
